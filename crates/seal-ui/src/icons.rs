//! One outline icon font for the editor. The licence sits beside the font file.
//!
//! Star filled uses the multi-star outline. This editor ships a single font face.

use std::sync::Arc;

use egui::{Align2, Color32, FontFamily, FontId, Pos2};

const ICON_FONT: &[u8] = include_bytes!("../../../assets/icons/icons.ttf");

const FAMILY: &str = "seal-icons";

/// Install the icon face once on this context. Later frames keep the same fonts.
pub fn install_icon_font(ctx: &egui::Context) {
    let key = egui::Id::new(FAMILY);
    if ctx.data(|data| data.get_temp::<bool>(key).unwrap_or(false)) {
        return;
    }
    let mut fonts = egui::FontDefinitions::default();
    fonts.font_data.insert(FAMILY.to_owned(), Arc::new(egui::FontData::from_static(ICON_FONT)));
    fonts.families.insert(icon_family(), vec![FAMILY.to_owned()]);
    ctx.set_fonts(fonts);
    ctx.data_mut(|data| data.insert_temp(key, true));
}

pub fn icon_family() -> FontFamily {
    FontFamily::Name(Arc::from(FAMILY))
}

/// The icon face is queued with `set_fonts` and only exists on the next pass.
pub fn icon_font_ready(ctx: &egui::Context) -> bool {
    let family = icon_family();
    ctx.fonts(|fonts| fonts.definitions().families.contains_key(&family))
}

pub fn paint_icon(painter: &egui::Painter, center: Pos2, icon: Icon, size: f32, color: Color32) {
    if icon == Icon::ViewHome {
        paint_home(painter, center, size, color);
        return;
    }
    if icon == Icon::EntityPlane {
        paint_entity_plane(painter, center, size, color);
        return;
    }
    if !icon_font_ready(painter.ctx()) {
        painter.ctx().request_repaint();
        return;
    }
    let family = icon_family();
    painter.text(
        center,
        Align2::CENTER_CENTER,
        icon.glyph().to_string(),
        FontId::new(size, family),
        color,
    );
}

/// The icon font has no house, so Home is drawn as the same kind of outline.
fn paint_home(painter: &egui::Painter, center: Pos2, size: f32, color: Color32) {
    let stroke = egui::Stroke::new((size * 0.08).max(1.0), color);
    let roof = center.y - size * 0.06;
    let eave = center.y + size * 0.02;
    let foot = center.y + size * 0.36;
    let left = center.x - size * 0.34;
    let right = center.x + size * 0.34;
    let wall_l = center.x - size * 0.22;
    let wall_r = center.x + size * 0.22;
    painter
        .line_segment([Pos2::new(center.x, center.y - size * 0.40), Pos2::new(left, eave)], stroke);
    painter.line_segment(
        [Pos2::new(center.x, center.y - size * 0.40), Pos2::new(right, eave)],
        stroke,
    );
    painter.line_segment([Pos2::new(wall_l, roof), Pos2::new(wall_l, foot)], stroke);
    painter.line_segment([Pos2::new(wall_r, roof), Pos2::new(wall_r, foot)], stroke);
    painter.line_segment([Pos2::new(wall_l, foot), Pos2::new(wall_r, foot)], stroke);
}

/// The font’s plane glyph is an aircraft. Draw a flat surface instead.
fn paint_entity_plane(painter: &egui::Painter, center: Pos2, size: f32, color: Color32) {
    let stroke = egui::Stroke::new((size * 0.08).max(1.0), color);
    let back_l = Pos2::new(center.x - size * 0.34, center.y - size * 0.18);
    let back_r = Pos2::new(center.x + size * 0.12, center.y - size * 0.18);
    let front_r = Pos2::new(center.x + size * 0.40, center.y + size * 0.22);
    let front_l = Pos2::new(center.x - size * 0.06, center.y + size * 0.22);
    painter.line_segment([back_l, back_r], stroke);
    painter.line_segment([back_r, front_r], stroke);
    painter.line_segment([front_r, front_l], stroke);
    painter.line_segment([front_l, back_l], stroke);
    let fold = Pos2::new(center.x + size * 0.26, center.y + size * 0.02);
    painter.line_segment([back_r, fold], stroke);
    painter.line_segment([fold, front_r], stroke);
}

/// Colour for an asset type. Kinds outside the named set use a neutral grey.
pub fn asset_tint(kind: &str) -> [u8; 3] {
    match kind {
        "scene" => [232, 146, 58],
        "mesh" => [62, 198, 214],
        "material" => [63, 185, 80],
        "texture" => [224, 68, 62],
        "sound" => [59, 130, 246],
        "animation" => [163, 113, 247],
        "script" => [138, 160, 184],
        "prefab" => [76, 141, 255],
        "data-table" => [212, 180, 74],
        _ => [154, 160, 166],
    }
}

/// Place-panel kind names (`cube`, `sphere`, `plane`, `empty`, `camera`, `light`).
pub fn place_icon(kind: &str) -> Icon {
    match kind {
        "cube" => Icon::EntityCube,
        "sphere" => Icon::EntitySphere,
        "cylinder" => Icon::EntityCylinder,
        "cone" => Icon::EntityCone,
        "capsule" => Icon::EntityCapsule,
        "plane" => Icon::EntityPlane,
        "camera" => Icon::EntityCamera,
        "light" => Icon::EntityLightPoint,
        "wind_area" => Icon::EntityLightDirectional,
        "water_area" => Icon::EntityCube,
        "gravity_area" => Icon::EntitySphere,
        "attractor" => Icon::EntityCone,
        "kill_zone" => Icon::EntityCube,
        "damage_zone" => Icon::EntityCube,
        "checkpoint" => Icon::EntityCapsule,
        "trigger_volume" => Icon::EntityCube,
        "sprite_mask" => Icon::EntitySprite,
        "character_2d" => Icon::EntityCapsule,
        _ => Icon::EntityEmpty,
    }
}

/// Outliner row icon from scene shape and role.
pub fn outliner_entity_icon(shape: &str, role: &str) -> Icon {
    if role == "folder" {
        return Icon::EntityFolder;
    }
    match shape {
        "none" | "" => match role {
            "light" => Icon::EntityLightPoint,
            "camera" => Icon::EntityCamera,
            "folder" => Icon::EntityFolder,
            _ => Icon::EntityEmpty,
        },
        other => place_icon(other),
    }
}

/// RGB tint for a 16 px outliner type icon.
pub fn outliner_entity_tint(shape: &str, role: &str) -> [u8; 3] {
    if role == "folder" {
        return [212, 167, 86];
    }
    match shape {
        "cube" => [62, 198, 214],
        "sphere" => [129, 212, 250],
        "cylinder" => [171, 130, 255],
        "cone" => [255, 152, 67],
        "capsule" => [186, 230, 145],
        "plane" => [120, 144, 156],
        "none" | "" => match role {
            "light" => [255, 213, 79],
            "camera" => [144, 164, 174],
            _ => [154, 160, 166],
        },
        _ => asset_tint(shape),
    }
}

